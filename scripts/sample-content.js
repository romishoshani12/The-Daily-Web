const perCategory = stories[0].length;
// Article i belongs to category i % 6. The first 30 articles are the original stories; each later round revisits them with a new angle.
function sampleArticle(i) {
  const category = i % CATEGORIES.length;
  const round = Math.floor(i / CATEGORIES.length);
  const story = stories[category][round % perCategory];
  const angle = Math.floor(round / perCategory);
  const followUp = angle > 0 ? followUps[(angle - 1) % followUps.length] : null;
  const repeat = angle > followUps.length ? ' (' + (Math.floor((angle - 1) / followUps.length) + 1) + ')' : '';
  return {
    title: followUp ? story.title + ' — ' + followUp.label + repeat : story.title,
    summary: followUp ? followUp.summary.replace('{topic}', story.topic) : story.summary,
    body: [disclaimer, ...story.body, ...(followUp ? [followUp.body] : [])].join('\n\n'),
    category: CATEGORIES[category],
    image: '/images/' + images[category] + '.svg'
  };
}

